//! The sample records the game starts with: the table of every sound's group, name key, priority,
//! voice kind, copies, scale, volume level, minimum distance, volume, pan and frequency, and the
//! copies for the cars after the first two.

use crate::audio::sample_records::VolumeLevel;
use rc2k_core::audio::voices::{
    BASE_SAMPLES, CODRIVER_COPIES, CODRIVER_FIRST, PLAYER_COPIES, SAMPLES, SampleRecord,
};

const BASE_COUNT: usize = BASE_SAMPLES as usize;
const SAMPLE_COUNT: usize = SAMPLES as usize;

/// The records as the game starts with them: per record its group, its name's key (the name's
/// position in the lists of `names_store::SampleNames`), priority, voice kind, copies, scale,
/// volume level, minimum distance (bits of an f32), volume, pan and frequency; the number is the
/// index and the first voice and place are 0.
pub(super) const fn first_records() -> [SampleRecord; SAMPLE_COUNT] {
    let base = base_records();
    let mut out = [base[0]; SAMPLE_COUNT];
    let mut n = 0;
    while n < SAMPLE_COUNT {
        // The copies for the cars after the first two repeat the records of the engine sounds,
        // then those of the co-driver's voices.
        let from = if n < BASE_COUNT {
            n
        } else if n < CODRIVER_COPIES as usize {
            (n - BASE_COUNT) % PLAYER_COPIES as usize
        } else {
            n - CODRIVER_COPIES as usize + CODRIVER_FIRST as usize
        };
        let mut record = base[from];
        record.number = n as u32;
        out[n] = record;
        n += 1;
    }
    out
}


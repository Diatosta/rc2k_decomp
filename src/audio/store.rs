/// One of `g_eaxRooms`' ten reverb settings (EAX's `EAX_REVERBPROPERTIES`, 16 bytes).
#[repr(C)]
pub struct EaxRoom {
    /// The preset's environment number.
    pub environment: Dword,
    pub volume: Float,
    pub decay: Float,
    pub damping: Float,
}


const fn script_words() -> [Word; SCRIPT_WORDS] {
    let mut words = [const { Word::new(0) }; SCRIPT_WORDS];
    let mut i = 0;
    while i < SCRIPT_WORDS {
        words[i] = Word::new(SCRIPT[i]);
        i += 1;
    }
    words
}

/// The credits; the first values are the image's.
impl Credits {
    pub const fn new() -> Self {
        Credits {
            top: Dword::new(0),
            clock: Dword::new(0),
            done: Dword::new(0),
            script: script_words(),
        }
    }
}

/// `race::roll_credits` (0x415FC2): mode 0 starts them (the clock, the top
/// the screen's height + 0x15E, the line count 0, tune 2 by `sound`); else draws the
/// script at 0x529858 (words: 1, 2, 7, 8 a string in fonts 0x51E8A4, 0x51E6A4, 0x51E564 (centred)
/// and 0x51E584 (at a sixteenth), each moving down a line; 3 / 4 a string left / right of the
/// middle (only 4 moves down); 5 three strings in columns; 6 a signed move; 9 nothing; any other
/// the end) from the top down, moves the top up a pixel for each 0x12 ms passed, and when the last
/// line is above -0xAF and the music has stopped, `Credits.done` 1.
pub fn roll_credits(
    frame: &Frame,
    eax: u32,
    canvas: &mut dyn Canvas,
    sound: &mut dyn FnMut(),
    system: &crate::system::owner::System,
    audio: &crate::audio::owner::Audio,
) -> Result<(), Refused> {
    let session = &system.session;
    // Converted: `rc2k_core::race::credits::{start_top, lay_out, catch_up, rolled_off}`.
    use crate::system::tick_count::tick_count;
    use rc2k_core::race::credits::{Font, catch_up, lay_out, rolled_off, start_top};
    let width = session.screen.width.get() as i32;
    let height: u32 = session.screen.height.get();
    if eax == 0 {
        frame.credits.clock.set(tick_count());
        let top = start_top(height);
        frame.credits.top.set(top);
        frame.credits.done.set(0);
        sound();
        return Ok(());
    }
    let font_of = |f: Font| {
        use crate::gfx::typefaces::fonts;
        match f.0 {
            1 => fonts::TITLE,
            2 => fonts::HEADING_23,
            3 => fonts::LABELS,
            4 => fonts::VALUES,
            7 => fonts::TIME,
            _ => fonts::NAME,
        }
    };
    // Read on to its end mark (two zero words, the script's last); a script without one is
    // refused at its end.
    let mut at = 0usize;
    let trap = Trap::new();
    let (lines, below) = lay_out(
        || {
            let v = frame.credits.script.get(at).map(Word::get);
            at += 1;
            trap.keep_read(v.ok_or(crate::errors::BadInput("the credits' script past its end")))
        },
        width,
        frame.credits.top.get() as i32,
        |f| font_of(f).object().line_height.get() as i32,
    );
    trap.finish()?;
    for line in lines {
        credit_line(line.id, font_of(line.font), line.x, line.y, canvas, system)?;
    }
    let (top, clock, _) = catch_up(
        frame.credits.top.get(),
        frame.credits.clock.get(),
        tick_count,
    );
    frame.credits.top.set(top);
    frame.credits.clock.set(clock);
    if !rolled_off(below, audio.state.music_stream.get().playing) {
        return Ok(());
    }
    frame.credits.done.set(1);
    Ok(())
}

/// `roll_credits`' tune in the game: `sound::play_tune_2`'s command, sent and waited for.
pub fn credits_tune() {
    crate::sound::play_tune_2::play_tune_2();
}

#[cfg(test)]
mod block_tests {
    use super::*;
    use crate::race::owner::race;
    use core::mem::offset_of;

    #[test]
    fn first_values_are_the_games() {
        crate::gfx::first_values_are_the_games(
            &race().frame.credits,
            CREDITS_START,
            CREDITS_START + CREDITS_LEN,
        );
    }

    #[test]
    fn moved_knows_the_block() {
        let frame = &race().frame;
        assert_eq!(offset_of!(Credits, script), 0x529858 - CREDITS_START);
        assert_eq!(
            crate::moved::place(CREDITS_START),
            frame.credits.top.addr() as usize
        );
        assert_eq!(
            crate::moved::place(0x529858),
            (crate::pointers::game_address(frame.credits.script.as_ptr())) as usize
        );
    }
}

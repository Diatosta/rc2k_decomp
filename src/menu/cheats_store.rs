/// The notice flag, the kept car and the cheats. Plain fields behind one `RefCell`: the game's
/// thread alone reads and writes them, each borrow lasting one statement.
pub struct Cheats(GameThread<RefCell<CheatValues>>);

/// The cheats' values.
#[derive(Clone, Copy)]
pub struct CheatValues {
    /// Set to 1 by the main menu before a frame (`menu::frame_callback` looks at it).
    pub notice_due: u32,
    /// The car shown on the car specification screen, kept over its visits.
    pub kept_car: u32,
    /// The cheats switched on, one bit each (`menu::apply_cheats`).
    pub cheats: u32,
    /// The `allsecretcars` / `secretcar` setting of `var\ral.cfg`.
    pub all_secret_cars: u32,
}

impl Cheats {
    pub const fn new() -> Self {
        Cheats(GameThread::new(RefCell::new(CheatValues {
            notice_due: 0x0,
            kept_car: 0x0,
            cheats: 0x0,
            all_secret_cars: 0xFFFFFFFF,
        })))
    }

    /// A copy of the values: no borrow outlives the statement that reads them.
    pub fn read(&self) -> CheatValues {
        *self.0.get().borrow()
    }

    /// The values, to write.
    pub fn write(&self) -> RefMut<'_, CheatValues> {
        self.0.get().borrow_mut()
    }
}

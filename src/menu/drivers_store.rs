/// The string id of name entry `entry` (a driver's first dword). The original does not
/// check the entry and reads on past the 180 (fixed: refused).
pub fn name_string(entry: u32) -> Result<u32, crate::errors::BadInput> {
    Ok(crate::menu::owner::menus()
        .cars
        .drivers
        .names
        .get(entry as usize)
        .ok_or(crate::errors::BadInput(
            "a driver's name entry past the 180",
        ))?
        .string
        .get())
}

/// IDA 0x73B674, the first byte of the piece.
pub const START: usize = 0x73B674;
/// IDA 0x742C98, the end of the piece.
pub const END: usize = 0x742C98;

/// Where IDA 0x73B674 is now (`moved::MOVED`'s home).
#[cfg(test)]
pub fn drivers_addr() -> u32 {
    crate::pointers::game_address(&raw const crate::menu::owner::MENUS.cars.drivers)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::moved::image_bytes;
    use core::mem::{offset_of, size_of};

    #[test]
    fn drivers_start_as_the_games() {
        assert_eq!(size_of::<DriverTable>(), END - START);
        assert_eq!(offset_of!(DriverTable, end), 0x741E84 - START);
        assert_eq!(offset_of!(DriverTable, names), 0x741E88 - START);
        assert_eq!(offset_of!(Driver, condition), 0x2C);
        assert_eq!(offset_of!(Driver, results), 0x5C);
        let mine = unsafe {
            std::slice::from_raw_parts(
                crate::pointers::host(drivers_addr()).cast_const(),
                END - START,
            )
        };
        assert_eq!(mine, &image_bytes(START, END - START)[..]);
    }
}

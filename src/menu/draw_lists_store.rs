//! The screens' draw lists, as handles into `rc2k_core::menu::tables::LISTS` (the one source
//! of the lists' functions): a screen names the list it puts in each of its list pointers
//! by the field here (`menu::screen_loop`), and `menu::run_list` / `menu::frame_callback`
//! walk the typed functions of the list. A list is named for the screen and the pointer it
//! is put in (`unread`, `draw`, `overlay`, `scene`, `setup`), or, where several screens
//! share it, for the pointers it is put in. Only the lists the Rust code names are here; the
//! table has them all.

use crate::menu::fn_list::FnList;

/// A draw list: its number in `LISTS`.
#[derive(Clone, Copy, Debug)]
pub struct DrawList(u16);

impl DrawList {
    /// The list from its function `k` on (a screen's may start at the end mark of
    /// another's: `k` is at most the list's length).
    pub fn from(&self, k: usize) -> FnList {
        FnList::draw(self.0, k)
    }

    /// The list.
    pub fn id(&self) -> FnList {
        self.from(0)
    }
}


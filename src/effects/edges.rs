//! `init_marks`' step 1, its second half (`sub_4C0F2E`; IDA, 2026-10-17): the kinds'
//! records scaled once, the kind's edge picture (`files\m\edgeNN.pcx`, 256 x 128) packed to
//! a byte a pixel, the shape tilt of the kind, then the masks and the two item kinds.

use crate::effects::kind_values::MARKS_KIND;
use crate::effects::store::game_addr;
use crate::effects::tilt_shape::SHAPE_TILT;
use crate::errors::{BadInput, Refused};
use crate::framework::rva;
use crate::gfx::picture_store::PICTURE;
use crate::math::x87;
use crate::pointers::GamePtr;
use crate::session::{Bytes, Dword, Float, Loose, read_bits};

pub const RESUME_RVA: usize = rva(0x4C0FFD); // loc_4C0FFD
const KINDS: u32 = 0x22;
const SETTING: u32 = 0x2708;
const SETTING_VALUE: u32 = 0xFFFF_7B2E;
const DIGITS: u32 = 12; // the two digits' place in the path
pub const EDGE_LEN: u32 = 0x8000;
const MOST_KIND: i32 = 0x16;

/// The kind, held to 0 .. 0x16.
fn clamped(kind: u32) -> u32 {
    (kind as i32).clamp(0, MOST_KIND) as u32
}

/// `effects::load_edges` (0x4C0F2E): once (`g_marksEdgesDone`, then `resume`) each kind's
/// record (`x87::scale_record` by 65536 / 1000) and its float less from 90; the settings'
/// +0x2708 0xFFFF7B2E; the kind (held to 0 .. 0x16) written as two digits into the edge
/// picture's path; that read (`gfx::read_picture_file`, at 256 x 128, the picture's sizes
/// kept round it); its pixels packed (the four bytes or'd, inverted) into
/// `g_marksEdgeMask`; the shape tilt the kind's float times 0.0175; then `make_masks`,
/// `set_up_windscreen_drops`, `set_up_windscreen_flakes` (and `nullsub_17`). Refuses a mark neither 0 nor
/// `resume`, before writing; a picture that is not read (the original then counts
/// 0x1FFFFFFF down and leaves with its stack one off), after the path is written.
pub fn load_edges(resume: u32) -> Result<(), Refused> {
    let done: u32 = EDGE_SETTINGS.done.get();
    if done != 0 && done != resume {
        return Err(BadInput("the edges' mark is neither 0 nor loc_4C0FFD").into());
    }
    if done == 0 {
        let boxes = KIND_BOXES.boxes.addr();
        let scale: [u32; 3] = read_bits(&EDGE_SETTINGS.scale);
        for k in 0..KINDS {
            x87::scale_record(
                crate::pointers::host(boxes + 0x30 * k) as *mut u32,
                scale[0],
                scale[1],
            );
            let f = &KIND_BOXES.kind_floats[k as usize];
            f.set_bits(x87::sub(scale[2], f.bits()));
        }
        EDGE_SETTINGS.done.set(resume);
    }
    let settings: u32 = crate::effects::setup::SETTINGS.pointer.get();
    GamePtr::new(settings + SETTING).write::<u32>(SETTING_VALUE, "a mark's field")?;
    let kind = clamped(MARKS_KIND.kind.bits());
    let path = EDGE_SETTINGS.path.addr();
    EDGE_SETTINGS
        .path
        .set(DIGITS as usize, (kind / 10) as u8 + b'0');
    EDGE_SETTINGS
        .path
        .set(DIGITS as usize + 1, (kind % 10) as u8 + b'0');
    let sizes: [u32; 3] = [
        PICTURE.width.get(),
        PICTURE.height.get(),
        PICTURE.row_bytes.get(),
    ];
    PICTURE.width.set(0x100u32);
    PICTURE.height.set(0x80u32);
    PICTURE.row_bytes.set(0xFFFF_FFFEu32);
    let read =
        crate::gfx::read_picture_file::read_picture_file(&crate::pointers::GamePtr::new(path));
    PICTURE.width.set(sizes[0]);
    PICTURE.height.set(sizes[1]);
    PICTURE.row_bytes.set(sizes[2]);
    if !read? {
        return Err(BadInput("the edge picture was not read").into());
    }
    let pixels = crate::gfx::picture::read_bytes(PICTURE.buffer.get(), 0, 4 * EDGE_LEN as usize)?;
    for (k, p) in pixels.as_chunks::<4>().0.iter().enumerate() {
        EDGE_MASK.mask.set(k, !(p[0] | p[1] | p[2] | p[3]));
    }
    let float = KIND_BOXES.kind_floats[kind as usize].bits();
    SHAPE_TILT
        .tilt
        .set_bits(x87::mul(float, EDGE_SETTINGS.tilt_scale.get()));
    crate::effects::masks::make_masks()?;
    crate::effects::shapes::set_up_windscreen_drops(game_addr(
        crate::effects::shapes::WINDSCREEN_DROPS.resume,
    ))?;
    crate::effects::shapes::set_up_windscreen_flakes(game_addr(
        crate::effects::shapes::WINDSCREEN_FLAKES_RESUME,
    ))?;
    Ok(())
}

const KIND_AT: u32 = 0x26A8; // the settings' kind

/// `effects::load_kind_data` (0x4C1235), `init_marks`' step 1: `g_marksKind` the settings'
/// +0x26A8; `nullsub_1` (twice, between them), `load_edges`, `load_splines`. Refuses as
/// its steps do.
pub fn load_kind_data() -> Result<(), Refused> {
    {
        let settings: u32 = crate::effects::setup::SETTINGS.pointer.get();
        let kind = GamePtr::new(settings + KIND_AT).read::<u32>("a mark's field")?;
        MARKS_KIND.kind.set_bits(kind);
        load_edges(game_addr(RESUME_RVA))?;
        crate::effects::splines::load_splines(game_addr(crate::effects::splines::RESUME_RVA))?;
    }
    Ok(())
}

/// The edge picture packed to a byte a pixel (`effects::edges`, `effects::run_windscreen_flakes`, `effects::windscreen_drops_frame`) (IDA 0x809BC3 .. 0x811BC3, the image's layout; phase 7, typed state).
#[repr(C)]
pub struct EdgeMask {
    /// 0x809BC3: `g_marksEdgeMask`: 256 x 128 cells, a byte set where an item dies.
    pub mask: Bytes<32768>,
}

pub static EDGE_MASK: EdgeMask = EdgeMask {
    mask: Bytes::new([0; 32768]),
};

impl EdgeMask {
    pub const START: usize = 0x809BC3;
    pub const LEN: usize = 0x8000;
    /// Where the byte IDA calls `START` is now (`moved::MOVED`'s home).
    pub fn home() -> usize {
        crate::pointers::game_address(&EDGE_MASK as *const EdgeMask) as usize
    }
}

#[cfg(test)]
mod edge_mask_tests {
    use super::*;

    #[test]
    fn edge_mask_starts_as_the_games() {
        use core::mem::offset_of;
        assert_eq!(size_of::<EdgeMask>(), EdgeMask::LEN);
        let p = &EDGE_MASK as *const EdgeMask as *const u8;
        let ours: Vec<u8> = (0..size_of::<EdgeMask>())
            .map(|i| unsafe { p.add(i).read() })
            .collect();
        assert!(
            ours == crate::moved::image_bytes(EdgeMask::START, EdgeMask::LEN),
            "EDGE_MASK starts differently from the image"
        );
        assert_eq!(offset_of!(EdgeMask, mask), 0x809BC3 - EdgeMask::START);
    }
}


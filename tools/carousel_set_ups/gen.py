#!/usr/bin/env python3
"""Makes src/scene/carousel_set_ups.rs from the JSON extract.py writes.

Usage: gen.py carousel.json > ../../src/scene/carousel_set_ups.rs

Menus whose function is more than stores and the fill are left out (None): they are
written by hand in set_up_carousel.rs.

Historical (2026-10-25): the generated file has since been typed by hand (phase 7: `Set(&cell,
v)`, `Run(|| &cell, v)` in place of `Store(address, v)`). Regenerating would undo that; edit
src/scene/carousel_set_ups.rs directly.
"""
import json
import sys

data = json.load(open(sys.argv[1]))
print("//! The carousels' set-ups that are only stores, one list a menu (`g_carouselMenu`),")
print("//! as `scene::set_up_carousel`'s per-menu functions make them. Generated by")
print("//! `tools/carousel_set_ups/gen.py` from the IDA extraction; do not edit by hand.")
print()
print("use crate::scene::set_up_carousel::Op::{self, Fill, Store};")
print()
menus = sorted(data.items(), key=lambda kv: int(kv[0]))
names = {}
for menu, entry in menus:
    function = entry["function"]
    plain = all(op[0] in ("store", "fill", "ret") for op in entry["ops"])
    if not plain:
        names[int(menu)] = None
        continue
    name = "MENU_%02X" % int(menu)
    names[int(menu)] = (name, function)
    lines = []
    for op in entry["ops"]:
        if op[0] == "store":
            lines.append("    Store(0x%X, 0x%X)," % (op[1], op[2]))
        elif op[0] == "fill":
            lines.append("    Fill,")
    print("/// `sub_%X`." % function)
    print("const %s: &[Op] = &[" % name)
    print("\n".join(lines))
    print("];")
    print()
count = max(names) + 1
print("/// By menu number; `None` for the menus written by hand.")
print("pub const PLAIN: [Option<&[Op]>; %d] = [" % count)
for menu in range(count):
    entry = names.get(menu)
    print("    Some(%s)," % entry[0] if entry else "    None,")
print("];")
print()
print("/// The function each menu's set-up is, for the self-test's copy.")
print("pub const FUNCTIONS: [usize; %d] = [" % count)
for menu in range(count):
    print("    0x%X," % data[str(menu)]["function"])
print("];")

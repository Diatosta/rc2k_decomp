#!/usr/bin/env python3
"""Makes src/scene/texture_steps.rs from the JSON extract_steps.py wrote.

usage: gen_steps.py steps.json src/scene/texture_steps.rs
"""
import json
import sys


def step(s, indent):
    pad = "    " * indent
    op = s["op"]
    if op == "text":
        text = s["text"].replace("\\", "\\\\").replace('"', '\\"')
        return f'{pad}Step::Text(c"{text}", {str(s["newline"]).lower()}),\n'
    if op == "number":
        return f'{pad}Step::Number({s["value"]:#x}, {str(s["newline"]).lower()}),\n'
    if op == "raise":
        return f'{pad}Step::Raise {{ level: {s["level"]}, tag: {s["tag"]:#x} }},\n'
    if op == "count":
        assert s["table"] == 0x5DC97C
        return f'{pad}Step::Count({s["index"]}),\n'
    if op == "try":
        return f"{pad}Step::Try,\n"
    if op == "release":
        return f"{pad}Step::Release,\n"
    if op == "count_needs":
        return f"{pad}Step::CountNeeds,\n"
    if op == "unless":
        inner = "".join(step(x, indent + 2) for x in s["steps"])
        return f'{pad}Step::Unless(\n{pad}    rva(0x{s["flag"]:X}),\n{pad}    &[\n{inner}{pad}    ],\n{pad}),\n'
    raise SystemExit(f"unknown op {op}")


def main():
    data = json.load(open(sys.argv[1]))
    # What the listing has besides the steps: the prologue and the two ways out.
    assert len(data["unknown"]) == 16, data["unknown"]
    steps = data["steps"]
    # The last three steps are where a successful try goes on; the two before them
    # are what is logged when every try has failed.
    done, failed, main = steps[-3:], steps[-5:-3], steps[:-5]
    assert done[0]["text"].startswith("Allocated") and failed[0]["text"].startswith("Cant")
    out = (
        "//! The steps of `scene::build_texture_catalogue` (0x42274B), as its listing has them.\n"
        "//! Generated by `tools/texture_catalogue/gen_steps.py` from what\n"
        "//! `tools/texture_catalogue/extract_steps.py` reads in IDA: do not edit.\n\n"
        "use crate::framework::rva;\n"
        "use crate::scene::build_texture_catalogue::Step;\n\n"
        "/// Until a try succeeds.\n"
        f"pub static STEPS: [Step; {len(main)}] = [\n"
        + "".join(step(s, 1) for s in main)
        + "];\n\n/// After every try has failed.\n"
        f"pub static FAILED: [Step; {len(failed)}] = [\n"
        + "".join(step(s, 1) for s in failed)
        + "];\n\n/// After a try that succeeded.\n"
        f"pub static DONE: [Step; {len(done)}] = [\n"
        + "".join(step(s, 1) for s in done)
        + "];\n\n/// Every call of the function, as an offset from its start.\n"
        f"pub static CALLS: [usize; {len(data['calls'])}] = [\n"
    )
    calls = data["calls"]
    for i in range(0, len(calls), 10):
        out += "    " + ", ".join(f"{c:#06x}" for c in calls[i : i + 10]) + ",\n"
    out += "];\n"
    open(sys.argv[2], "w").write(out)


main()

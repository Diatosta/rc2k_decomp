#!/usr/bin/env python3
"""Splits src/race/store_data.rs (one RUNS table of the race block) into one file per store.

Run once from the repository root: python3 tools/runs_split/split_runs.py
(it reads the old file from git: `git show HEAD:src/race/store_data.rs`, so it can be re-run).

Pieces: every store whose file calls `first_values` (its `START` .. `END`), plus the
block's ranges no such store covers (`OWN` in src/race/store.rs, named `own_<ida>`), plus any
other stretch between two boundaries that holds non-zero bytes (`gap_<ida>`). Each run is
cut at the piece boundaries; offsets in a piece are relative to its start. Prints every run
that was cut. A piece's file is named `<module>_<store>` (`race_tables`, `physics_tables`).
"""
import re, subprocess, os, sys, hashlib

BLOCK = 0x5BEC48
END_BLOCK = 0x747AD8
src = subprocess.check_output(["git", "show", "HEAD:src/race/store_data.rs"]).decode()
runs = []
for m in re.finditer(r"\(\s*(0x[0-9a-f]+),\s*&\[(.*?)\],?\s*\)", src, re.S):
    data = bytes(int(x, 16) for x in re.findall(r"0x[0-9a-f]{2}", m.group(2)))
    runs.append((BLOCK + int(m.group(1), 16), data))
assert len(runs) == 1354, len(runs)

ranges = {}  # name -> (start, end)
files = subprocess.check_output(["grep", "-rl", "first_values::<", "src"]).decode().split()
for f in files:
    if "test_support" in f or f.endswith(("race/store.rs", "groups_store.rs", "lamp_work.rs", "view_course.rs")):
        continue
    t = open(f).read()
    s = re.search(r"pub const START: usize = (0x[0-9A-Fa-f]+);", t)
    e = re.search(r"pub const END: usize = (0x[0-9A-Fa-f]+);", t)
    assert s and e, f
    name = os.path.basename(f)[:-3]
    name = name[:-6] if name.endswith("_store") else name
    name = os.path.basename(os.path.dirname(f)) + "_" + name
    assert name not in ranges, name
    ranges[name] = (int(s.group(1), 16), int(e.group(1), 16))
own = [(0x5BEC48, 0x5BEC78), (0x5C2714, 0x5C291C), (0x5C5E50, 0x5C5F48), (0x5C5FB8, 0x5C6604),
       (0x5C6610, 0x5C6924), (0x5C6948, 0x5C694C), (0x5C7908, 0x5C790C), (0x5EA8C8, 0x5EB100),
       (0x5EB104, 0x60101C), (0x60230C, 0x60410C), (0x60526C, 0x60626C), (0x60B0BD, 0x60B2CC),
       (0x60B2D0, 0x613828), (0x61FE18, 0x620458), (0x620474, 0x621480), (0x6218B0, 0x6218F0),
       (0x6218F4, 0x621900), (0x621A84, 0x62290C), (0x622910, 0x6235E8), (0x628A44, 0x62DA44),
       (0x64098C, 0x64158C), (0x64BB88, 0x6D13FE), (0x71CA60, 0x731B82)]
for s, e in own:
    ranges["own_%x" % s] = (s, e)
spans = sorted(ranges.items(), key=lambda kv: kv[1])
for (a, (s1, e1)), (b, (s2, e2)) in zip(spans, spans[1:]):
    assert e1 <= s2, ("overlap", a, b)

# pieces: named ranges, then the uncovered stretches (only where runs fall)
pieces = [(s, e, n) for n, (s, e) in spans]
cur = BLOCK
cover = []
for s, e, n in pieces:
    if s > cur:
        cover.append((cur, s, "gap_%x" % cur))
    cur = e
if cur < END_BLOCK:
    cover.append((cur, END_BLOCK, "gap_%x" % cur))
pieces += cover
pieces.sort()

out = {n: [] for _, _, n in pieces}
crossings = []
for a, d in runs:
    pos = a
    parts = 0
    for s, e, n in pieces:
        lo, hi = max(a, s), min(a + len(d), e)
        if lo < hi:
            out[n].append((lo - s, d[lo - a:hi - a]))
            parts += 1
    assert parts >= 1, hex(a)
    if parts > 1:
        crossings.append((a, len(d), parts))
used = [(s, e, n) for s, e, n in pieces if out[n]]
assert sum(len(d) for n in out for _, d in out[n]) == sum(len(d) for _, d in runs)

os.makedirs("src/race/store_data", exist_ok=True)
for f in os.listdir("src/race/store_data"):
    os.remove("src/race/store_data/" + f)

def fmt(r):
    lines = []
    for off, d in r:
        lines.append("    (0x%x, &[%s])," % (off, ", ".join("0x%02x" % b for b in d)))
    return "\n".join(lines)

for s, e, n in used:
    with open("src/race/store_data/%s.rs" % n, "w") as fh:
        fh.write("//! First values of the race block, IDA 0x%X .. 0x%X (generated by tools/runs_split).\n\n" % (s, e))
        fh.write("/// `(offset from 0x%X, bytes)`, in order, apart.\n" % s)
        fh.write("pub const RUNS: &[(usize, &[u8])] = &[\n%s\n];\n" % fmt(out[n]))
with open("src/race/store_data/mod.rs", "w") as fh:
    fh.write("//! The race core's first values: the non-zero bytes of the image's IDA 0x%X .. 0x%X, one\n" % (BLOCK, END_BLOCK))
    fh.write("//! file per store (generated by tools/runs_split; a run that crossed two stores' edge is cut).\n")
    fh.write("//! `Piece::runs` offsets count from the piece's `start`.\n\n")
    fh.write("pub struct Piece {\n    /// IDA's address of the piece's first byte.\n    pub start: usize,\n    pub runs: &'static [(usize, &'static [u8])],\n}\n\n")
    for s, e, n in used:
        fh.write("mod %s;\n" % n)
    fh.write("\n/// In address order, apart.\npub const PIECES: &[Piece] = &[\n")
    for s, e, n in used:
        fh.write("    Piece { start: 0x%X, runs: %s::RUNS },\n" % (s, n))
    fh.write("];\n")
digest = hashlib.sha256(b"".join(a.to_bytes(4, "little") + bytes(d) for a, d in runs)).hexdigest()
print("pieces with runs:", len(used), "of", len(pieces), "; absolute-run digest", digest)
print("crossing runs (abs address, length, pieces):")
for a, l, p in crossings:
    print("  0x%X len %d -> %d pieces" % (a, l, p))

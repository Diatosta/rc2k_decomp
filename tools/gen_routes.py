#!/usr/bin/env python3
"""Writes src/routes.rs (conversion, 2026-10-22): for every hook with a hook-free `entry`
(its Rust version, a refusal handed back), the RVA of its function -> that entry, for
`calls::call`, which Rust callers use where they named a game function by its address.
The tables' functions (menus, draw lists) are `menu::table_routes`', not here. A hook
that is gone keeps the route `routes.rs` already has: the build checks it still exists.

    tools/gen_routes.py > src/routes.rs
"""
import glob
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')


def module_path(path):
    rel = os.path.relpath(path, os.path.join(ROOT, 'src'))[:-3].split(os.sep)
    if rel[-1] == 'mod':
        rel = rel[:-1]
    return 'crate::' + '::'.join(rel)


def found():
    """RAL address -> (hook name, the entry's path), for hook files with an entry at their
    top level."""
    out = {}
    for path in sorted(glob.glob(os.path.join(ROOT, 'src', '**', '*.rs'), recursive=True)):
        s = open(path).read()
        if not re.search(r'^pub fn entry\((?:r|_): &mut (?:crate::framework::)?Regs\)', s, re.M):
            continue
        hooks = re.findall(r'^pub static HOOK: RawHook =\s*RawHook::new\(\s*"([^"]+)",\s*'
                           r'rva\((0x[0-9A-Fa-f]+)\)', s, re.M)
        if not hooks:
            # a hook removed (phase 4): its header still names the function and its address
            hooks = re.findall(r'\A//! `((?:[a-z0-9_]+::)+[a-z0-9_]+)` \((0x[0-9A-Fa-f]+)[,;)]', s)
        if len(hooks) != 1:
            continue
        name, at = hooks[0]
        out[int(at, 16)] = (name, module_path(path) + '::entry')
    return out


def kept():
    """RAL address -> (name, path) from the routes as they are."""
    path = os.path.join(ROOT, 'src', 'routes.rs')
    if not os.path.exists(path):
        return {}
    return {int(m.group(1), 16): (m.group(3), m.group(2)) for m in re.finditer(
        r'^        (0x[0-9A-F]+) => Some\(([\w:]+)\(r\)\), // (\S+)$', open(path).read(),
        re.M)}


# The log's level-setting wrappers (edx: dl the newline, dh the level less one, then a jump
# on) and `log_newline_l1` (0x4013DE: an empty line at level 1, every register kept).
WRAPPERS = [
    (0x401427, 0x000, 0x4013CB, 'log_write_l1'), (0x40142B, 0x001, 0x4013CB, 'log_write_l1_nl'),
    (0x401432, 0x100, 0x4013CB, 'log_write_l2'), (0x401439, 0x101, 0x4013CB, 'log_write_l2_nl'),
    (0x401472, 0x000, 0x401440, 'log_int_l1'), (0x401476, 0x001, 0x401440, 'log_int_l1_nl'),
    (0x40147D, 0x100, 0x401440, 'log_int_l2'), (0x401484, 0x101, 0x401440, 'log_int_l2_nl'),
    (0x4014BF, 0x000, 0x40148B, 'log_int_fmt_l1'),
    (0x4015CF, 0x000, 0x4014D8, 'log_float_l1'), (0x4015D6, 0x001, 0x4014D8, 'log_float_l1_nl'),
    (0x401622, 0x000, 0x4015F4, 'log_hex8_l1'), (0x401626, 0x001, 0x4015F4, 'log_hex8_l1_nl'),
    (0x40162D, 0x100, 0x4015F4, 'log_hex8_l2'), (0x401634, 0x101, 0x4015F4, 'log_hex8_l2_nl'),
    (0x4016B0, 0x000, 0x401682, 'log_hex4_l1'),
]

routes = kept()
routes.update(found())
special = {}
for at, edx, target, name in WRAPPERS:
    special[at] = ('logfile::' + name,
                   f'{{ r.edx = 0x{edx:X}; {routes[target][1]}(r) }}')
special[0x4013DE] = ('logfile::log_newline_l1',
                     '{ crate::logfile::log_write::log_newline_l1(); Ok(()) }')
# the installer's two frames: hooks of a module each inside `install_frames.rs`
special[0x413295] = ('install::progress_frame',
                     'crate::install::install_frames::progress::entry(r)')
special[0x413340] = ('install::copying_frame',
                     'crate::install::install_frames::copying::entry(r)')
out = [
    '//! Generated by `tools/gen_routes.py`: do not edit by hand. The Rust version of each',
    '//! function of the game\'s that has a hook-free `entry`, by its address (as an RVA);',
    '//! `calls.rs` calls these.',
    '',
    'use crate::errors::Refused;',
    'use crate::framework::{IMAGE_BASE, Regs};',
    '',
    '/// Runs the function at `at` (an RVA) with `r`, if it has a Rust version here.',
    '#[rustfmt::skip]',
    'pub fn by_rva(at: usize, r: &mut Regs) -> Option<Result<(), Refused>> {',
    '    match at.wrapping_add(IMAGE_BASE) {',
]
for at in sorted(set(routes) | set(special)):
    if at in special:
        name, expr = special[at]
        out.append(f'        0x{at:X} => Some({expr}), // {name}')
    else:
        name, path = routes[at]
        out.append(f'        0x{at:X} => Some({path}(r)), // {name}')
out += ['        _ => None,', '    }', '}']
print('\n'.join(out))

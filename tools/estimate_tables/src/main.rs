//! The tables of `rc2k_core::math::estimates`, from this processor's `rcpss` / `rsqrtss`.
//!
//! `cargo run --release -- generate > ../../rc2k_core/src/math/estimate_tables.rs` writes
//! the tables (they were made on an AMD Ryzen 7 5800X; do not regenerate on another
//! processor, or replays change). `cargo run --release -- verify` compares the core's
//! functions with this processor's instructions over all 2^32 inputs and counts the
//! differences: 0 on the processor the tables came from, and on another the measure of how
//! far its estimates are from those.

#[cfg(target_arch = "x86")]
use std::arch::x86::{_mm_cvtss_f32, _mm_rcp_ss, _mm_rsqrt_ss, _mm_set_ss};
#[cfg(target_arch = "x86_64")]
use std::arch::x86_64::{_mm_cvtss_f32, _mm_rcp_ss, _mm_rsqrt_ss, _mm_set_ss};

use rc2k_core::math::estimates::{reciprocal_estimate, reciprocal_root_estimate};

fn rcp(a: f32) -> f32 {
    // SAFETY: SSE is part of every x86 target's baseline.
    unsafe { _mm_cvtss_f32(_mm_rcp_ss(_mm_set_ss(a))) }
}

fn rsqrt(a: f32) -> f32 {
    // SAFETY: as `rcp`.
    unsafe { _mm_cvtss_f32(_mm_rsqrt_ss(_mm_set_ss(a))) }
}

fn dump(name: &str, doc: &str, v: &[u32]) {
    println!("{doc}");
    println!("pub(super) static {name}: [u32; 4096] = [");
    for c in v.chunks(8) {
        let row: Vec<String> = c.iter().map(|x| format!("0x{x:08X}")).collect();
        println!("    {},", row.join(", "));
    }
    println!("];");
}

fn octave(f: fn(f32) -> f32, exponent: u32) -> Vec<u32> {
    (0..4096u32)
        .map(|i| f(f32::from_bits((exponent << 23) | (i << 11))).to_bits())
        .collect()
}

fn generate() {
    println!(
        "//! The estimate tables (`math::estimates`), generated by `tools/estimate_tables` from an AMD"
    );
    println!(
        "//! Ryzen 7 5800X's `rcpss` / `rsqrtss`, by the input's top 12 mantissa bits. Do not edit."
    );
    println!();
    dump(
        "RECIPROCAL",
        "/// `rcpss` of 1.m (exponent 127), for m's top 12 bits.",
        &octave(rcp, 127),
    );
    println!();
    dump(
        "ROOT_EVEN",
        "/// `rsqrtss` of 1.m (exponent 127, an even power of two), for m's top 12 bits.",
        &octave(rsqrt, 127),
    );
    println!();
    dump(
        "ROOT_ODD",
        "/// `rsqrtss` of 2 x 1.m (exponent 128, an odd power of two), for m's top 12 bits.",
        &octave(rsqrt, 128),
    );
}

fn verify() {
    let (mut reciprocal, mut root) = (0u64, 0u64);
    for x in 0..=u32::MAX {
        let a = f32::from_bits(x);
        let (h, m) = (rcp(a).to_bits(), reciprocal_estimate(a).to_bits());
        if h != m {
            reciprocal += 1;
            if reciprocal <= 5 {
                println!("rcpss {x:#010x}: processor {h:#010x}, table {m:#010x}");
            }
        }
        let (h, m) = (rsqrt(a).to_bits(), reciprocal_root_estimate(a).to_bits());
        if h != m {
            root += 1;
            if root <= 5 {
                println!("rsqrtss {x:#010x}: processor {h:#010x}, table {m:#010x}");
            }
        }
    }
    println!("differences over 2^32 inputs: rcpss {reciprocal}, rsqrtss {root}");
}

fn main() {
    match std::env::args().nth(1).as_deref() {
        Some("generate") => generate(),
        Some("verify") => verify(),
        _ => eprintln!("usage: estimate_tables generate | verify"),
    }
}

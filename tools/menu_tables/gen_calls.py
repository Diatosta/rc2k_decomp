#!/usr/bin/env python3
"""Writes src/menu/table_routes.rs (typed tables, 2026-10-22): for each function the menus'
items (`ItemFn`) and the draw lists (`ScreenFn`) name, the Rust version that runs it: the
`entry` of the hook with the function's IDA name (a hook file's, a macro-made hook's
module's, or a hook module's inside a file). The enums are read from
rc2k_core/src/menu/tables_data.rs; the few functions with no hook of their own are in
`SPECIAL` below. A function whose hook is gone (removed once the tables ran it) keeps the
route `table_routes.rs` already has: the build checks that it still exists.

    tools/menu_tables/gen_calls.py > src/menu/table_routes.rs
"""
import glob
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
DATA = os.path.join(ROOT, 'rc2k_core', 'src', 'menu', 'tables_data.rs')

# IDA name -> the expression that runs it (`r`: the registers), for the functions with no
# hook: trampolines into a hook, and the ones that do nothing.
SPECIAL = {
    'menu::empty_draw_step': 'Ok(())',
    'menu::network_settings_item':
        'crate::net::lobby::lobby_entry(r, crate::net::settings_loop::settings_loop)',
    'menu::join_network_game':
        '{\n            r.eax = 2;\n'
        '            crate::net::lobby::lobby_entry(r, crate::net::start_link::start_link)\n        }',
    'menu::host_network_game':
        '{\n            r.eax = 1;\n'
        '            crate::net::lobby::lobby_entry(r, crate::net::start_link::start_link)\n        }',
}


def enums():
    """{enum: [(variant, IDA name)]} from the generated tables."""
    out, current, doc = {}, None, None
    for line in open(DATA):
        m = re.match(r'pub enum (\w+) \{', line)
        if m:
            current = m.group(1)
            out[current] = []
            continue
        if current is None:
            continue
        if line.startswith('}'):
            current = None
            continue
        m = re.match(r'\s*/// `([^`]+)`', line)
        if m:
            doc = m.group(1).replace('__', '::')
            continue
        m = re.match(r'\s*(\w+),', line)
        if m:
            out[current].append((m.group(1), doc))
    return out


def module_path(path):
    rel = os.path.relpath(path, os.path.join(ROOT, 'src'))[:-3].split(os.sep)
    if rel[-1] == 'mod':
        rel = rel[:-1]
    return 'crate::' + '::'.join(rel)


def enclosing_modules(s, at):
    """The `pub mod x {` blocks open at `at`."""
    stack = []
    depth = 0
    opened = {}
    i = 0
    for m in re.finditer(r'pub mod (\w+) \{|\{|\}', s[:at]):
        if m.group(0) == '}':
            depth -= 1
            if stack and stack[-1][1] == depth:
                stack.pop()
        else:
            if m.group(1):
                stack.append((m.group(1), depth))
            depth += 1
    return [name for name, _ in stack]


def entries():
    """IDA name -> the path of its hook's `entry`."""
    found = {}
    for path in glob.glob(os.path.join(ROOT, 'src', '**', '*.rs'), recursive=True):
        s = open(path).read()
        # (a file made by `starter_hook!` / `flow_hook!` has its entry in the macro)
        if 'fn entry(' not in s and not re.search(r'\b\w+_hook!\(', s):
            continue
        for m in re.finditer(r'"((?:[a-z0-9_]+::)+[a-z0-9_]+)"', s):
            name = m.group(1)
            before = s[max(0, m.start() - 200):m.start()]
            macro = re.search(r'\b(\w+)!\(\s*(\w+)\s*,\s*$', before)
            if re.search(r'RawHook::new\(\s*$', before):
                mods = enclosing_modules(s, m.start())
            elif macro and macro.group(1) not in ('format', 'log', 'concat'):
                mods = enclosing_modules(s, m.start()) + [macro.group(2)]
            elif re.search(r'\b\w+_hook!\(\s*$', before):
                mods = enclosing_modules(s, m.start())
            else:
                continue
            found.setdefault(name, '::'.join([module_path(path)] + mods) + '::entry')
    return found


def kept_routes():
    """`Enum::Variant` -> the arm's expression, from the routes as they are."""
    path = os.path.join(ROOT, 'src', 'menu', 'table_routes.rs')
    if not os.path.exists(path):
        return {}
    s = open(path).read()
    return {m.group(1): m.group(2) for m in re.finditer(
        r'^        ((?:ItemFn|ScreenFn)::\w+) => (.+?)(?=^        (?:ItemFn|ScreenFn)::|^    \})',
        s, re.M | re.S)}


def main():
    paths = entries()
    kept = kept_routes()
    out = [
        '//! Generated by `tools/menu_tables/gen_calls.py`: do not edit by hand. Which Rust',
        '//! version runs each function the menus\' items and the draw lists name (typed',
        '//! tables, `rc2k_core::menu::tables`); `table_calls.rs` calls these.',
        '',
        'use crate::errors::Refused;',
        'use crate::framework::Regs;',
        'use rc2k_core::menu::tables::{ItemFn, ScreenFn};',
        '',
    ]
    missing = []
    for enum, fn in (('ItemFn', 'item_fn'), ('ScreenFn', 'screen_fn')):
        out += [
            f'/// Runs `f` with the registers in `r`.',
            f'pub fn {fn}(f: {enum}, r: &mut Regs) -> Result<(), Refused> {{',
            '    match f {',
        ]
        for variant, name in enums()[enum]:
            if variant == 'Nothing':
                out.append(f'        {enum}::Nothing => Ok(()),')
            elif name in SPECIAL:
                out.append(f'        {enum}::{variant} => {SPECIAL[name]}')
                if not SPECIAL[name].endswith('}'):
                    out[-1] += ','
            elif name in paths:
                out.append(f'        {enum}::{variant} => {paths[name]}(r),')
            elif f'{enum}::{variant}' in kept:
                out.append(f'        {enum}::{variant} => ' + kept[f'{enum}::{variant}'].rstrip())
            else:
                missing.append(name)
        out += ['    }', '}', '']
    if missing:
        sys.exit('no entry for: ' + ', '.join(missing))
    print('\n'.join(out).rstrip('\n'))


main()

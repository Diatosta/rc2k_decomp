#!/usr/bin/env python3
"""Writes rc2k_core/src/menu/tables_data.rs from `extract.py`'s JSON: the enums of the
functions the menus' items (`ItemFn`) and the draw lists (`ScreenFn`) name, of the fonts the
menus name (`MenuFont`), each with its RAL address, and the 96 menus and 301 draw lists.
Every do-nothing function (`nullsub_*`) is
`Nothing`, mapped back to the first of them.

    tools/menu_tables/gen.py <scratch>/menu_tables.json > rc2k_core/src/menu/tables_data.rs
"""
import json
import re
import sys

d = json.load(open(sys.argv[1]))
functions = {int(k): v for k, v in d['functions'].items()}
fonts = {int(k): v for k, v in d['fonts'].items()}


def camel(name):
    return ''.join(p[:1].upper() + p[1:] for p in re.split(r'_+', name) if p)


def variant_names(addresses):
    """IDA's names as variants: the last part camel-cased, the module in front where two
    modules share a name; all `nullsub_*` one `Nothing`."""
    parts = {}
    for a in addresses:
        name = functions[a].replace('__', '::')
        if name.startswith('nullsub_'):
            parts[a] = ('', 'Nothing')
            continue
        module, _, last = name.rpartition('::')
        parts[a] = (module, camel(last))
    count = {}
    for a, (m, v) in parts.items():
        count.setdefault(v, set()).add(m)
    out = {}
    for a, (m, v) in parts.items():
        out[a] = v if v == 'Nothing' or len(count[v]) == 1 else camel(m) + v
    return out


def enum(name, doc, addresses, names):
    variants = {}
    for a in sorted(addresses):
        variants.setdefault(names[a], a)  # Nothing: the first nullsub
    lines = [f'/// {doc}', '#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]',
             f'pub enum {name} {{']
    for v, a in sorted(variants.items(), key=lambda x: x[1]):
        label = functions.get(a, fonts.get(a))
        if label and label.startswith('nullsub_'):
            lines.append('    /// A function that does nothing.')
        else:
            lines.append(f'    /// `{label}`')
        lines.append(f'    {v},')
    lines.append('}')
    lines.append('')
    lines.append(f'impl {name} {{')
    lines.append(f'    pub const ALL: &[{name}] = &[')
    for v in sorted(variants, key=lambda v: variants[v]):
        lines.append(f'        {name}::{v},')
    lines.append('    ];')
    lines.append('')
    lines.append('    /// The address RAL.EXE keeps it at.')
    lines.append('    pub const fn ral(self) -> u32 {')
    lines.append('        match self {')
    for v, a in sorted(variants.items(), key=lambda x: x[1]):
        lines.append(f'            {name}::{v} => 0x{a:X},')
    lines.append('        }')
    lines.append('    }')
    lines.append('')
    lines.append('    /// The one RAL.EXE keeps at `at`.')
    lines.append('    pub const fn from_ral(at: u32) -> Option<Self> {')
    lines.append('        Some(match at {')
    for a in sorted(addresses):
        lines.append(f'            0x{a:X} => {name}::{names[a]},')
    lines.append('            _ => return None,')
    lines.append('        })')
    lines.append('    }')
    lines.append('}')
    return lines


item_fns, screen_fns = set(), set()
for m in d['menus']:
    for it in m['items']:
        item_fns.update(it[13:18])
for l in d['lists']:
    screen_fns.update(l['functions'])

item_names = variant_names(item_fns)
screen_names = variant_names(screen_fns)
font_names = {a: 'At' + format(a, 'X') for a in fonts}

out = [
    '//! Generated by `tools/menu_tables/gen.py` from RAL.EXE\'s menus and draw lists (read by',
    '//! `tools/menu_tables/extract.py`): do not edit by hand. The types are in `tables.rs`.',
    '',
    '#![allow(clippy::unreadable_literal)]',
    '',
    'use super::tables::{DrawList, Menu, MenuItem, MenuLabel};',
    '',
]
out += enum('ItemFn', "A function a menu item names (its keys' and its action's).",
            item_fns, item_names)
out.append('')
out += enum('ScreenFn', 'A function a draw list names.', screen_fns, screen_names)
out.append('')
out += ['/// A font the menus name, by the address RAL.EXE keeps it at.',
        '#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]', 'pub enum MenuFont {']
for a in sorted(fonts):
    out += [f'    {font_names[a]},']
out += ['}', '', 'impl MenuFont {', '    pub const ALL: &[MenuFont] = &[']
out += [f'        MenuFont::{font_names[a]},' for a in sorted(fonts)]
out += ['    ];', '', '    /// The address RAL.EXE keeps it at.', '    pub const fn ral(self) -> u32 {',
        '        match self {']
out += [f'            MenuFont::{font_names[a]} => 0x{a:X},' for a in sorted(fonts)]
out += ['        }', '    }', '', '    /// The one RAL.EXE keeps at `at`.',
        '    pub const fn from_ral(at: u32) -> Option<Self> {', '        Some(match at {']
out += [f'            0x{a:X} => MenuFont::{font_names[a]},' for a in sorted(fonts)]
out += ['            _ => return None,', '        })', '    }', '}', '']


def i32(v):
    return v - (1 << 32) if v >= 1 << 31 else v


def font(v):
    if v not in fonts:
        raise SystemExit(f'{v:#x} is not a font the extract knows')
    return f'MenuFont::{font_names[v]}'


def item(w):
    f = lambda a: f'ItemFn::{item_names[a]}'
    return (
        f'        MenuItem {{ x: {i32(w[0])}, y: {i32(w[1])}, width_or_text_x: {i32(w[2])}, '
        f'alignment_or_text_y: {i32(w[3])}, id: 0x{w[4]:X}, string: 0x{w[5]:X}, font: {font(w[6])}, '
        f'behind: 0x{w[7]:X}, sprites: 0x{w[8]:X}, links: [0x{w[9]:X}, 0x{w[10]:X}, 0x{w[11]:X}, 0x{w[12]:X}], '
        f'on_key: [{f(w[13])}, {f(w[14])}, {f(w[15])}, {f(w[16])}], action: {f(w[17])}, '
        f'skip_mark: 0x{w[18]:X}, measuring_font: {font(w[19])}, highlight_font: {font(w[20])}, '
        f'action_value: 0x{w[21]:X}, spaced: 0x{w[22]:X} }},')


menus = sorted(d['menus'], key=lambda m: m['at'])
out.append(f'pub static MENUS: [Menu; {len(menus)}] = [')
for m in menus:
    out.append(f'    Menu {{ at: 0x{m["at"]:X}, referenced: {str(m["referenced"]).lower()}, '
               f'labels_at: 0x{m["labels_at"]:X}, labels: &[')
    for l in m['labels']:
        out.append(f'        MenuLabel {{ x: {i32(l[0])}, y: {i32(l[1])}, font: {font(l[2])}, '
                   f'string: 0x{l[3]:X} }},')
    out.append('    ], items: &[')
    out += [item(w) for w in m['items']]
    out.append('    ] },')
out.append('];')
out.append('')

lists = sorted(d['lists'], key=lambda l: l['at'])
out.append(f'pub static LISTS: [DrawList; {len(lists)}] = [')
for l in lists:
    fns = ', '.join(f'ScreenFn::{screen_names[a]}' for a in l['functions'])
    out.append(f'    DrawList {{ at: 0x{l["at"]:X}, referenced: {str(l["referenced"]).lower()}, '
               f'functions: &[{fns}] }},')
out.append('];')
print('\n'.join(out))

/// SHA-256 of `data`.
pub fn sha256(data: &[u8]) -> [u8; KEY_LEN] {
    let mut h: [u32; 8] = [
        0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab,
        0x5be0cd19,
    ];
    let mut message = data.to_vec();
    message.push(0x80);
    while message.len() % 64 != 56 {
        message.push(0);
    }
    message.extend(((data.len() as u64) * 8).to_be_bytes());
    for block in message.as_chunks::<64>().0 {
        let mut w = [0u32; 64];
        for (i, word) in block.as_chunks::<4>().0.iter().enumerate() {
            w[i] = u32::from_be_bytes(*word);
        }
        for i in 16..64 {
            let s0 = w[i - 15].rotate_right(7) ^ w[i - 15].rotate_right(18) ^ (w[i - 15] >> 3);
            let s1 = w[i - 2].rotate_right(17) ^ w[i - 2].rotate_right(19) ^ (w[i - 2] >> 10);
            w[i] = w[i - 16]
                .wrapping_add(s0)
                .wrapping_add(w[i - 7])
                .wrapping_add(s1);
        }
        let mut v = h;
        for i in 0..64 {
            let s1 = v[4].rotate_right(6) ^ v[4].rotate_right(11) ^ v[4].rotate_right(25);
            let ch = (v[4] & v[5]) ^ (!v[4] & v[6]);
            let t1 = v[7]
                .wrapping_add(s1)
                .wrapping_add(ch)
                .wrapping_add(K[i])
                .wrapping_add(w[i]);
            let s0 = v[0].rotate_right(2) ^ v[0].rotate_right(13) ^ v[0].rotate_right(22);
            let maj = (v[0] & v[1]) ^ (v[0] & v[2]) ^ (v[1] & v[2]);
            let t2 = s0.wrapping_add(maj);
            v = [
                t1.wrapping_add(t2),
                v[0],
                v[1],
                v[2],
                v[3].wrapping_add(t1),
                v[4],
                v[5],
                v[6],
            ];
        }
        for (a, b) in h.iter_mut().zip(v) {
            *a = a.wrapping_add(b);
        }
    }
    let mut out = [0u8; KEY_LEN];
    for (chunk, word) in out.as_chunks_mut::<4>().0.iter_mut().zip(h) {
        *chunk = word.to_be_bytes();
    }
    out
}

/// The key a password makes with a salt: what the host keeps in its password's place and a
/// joiner works out from the salt the host names.
pub fn key(salt: &[u8; SALT_LEN], password: &[u8]) -> [u8; KEY_LEN] {
    let mut seed = salt.to_vec();
    seed.extend_from_slice(password);
    let mut key = sha256(&seed);
    for _ in 1..ROUNDS {
        let mut again = key.to_vec();
        again.extend_from_slice(salt);
        key = sha256(&again);
    }
    key
}

/// The answer to a challenge: a hash of the challenge and the key.
pub fn proof(challenge: &[u8; SALT_LEN], key: &[u8; KEY_LEN]) -> [u8; KEY_LEN] {
    let mut data = challenge.to_vec();
    data.extend_from_slice(key);
    sha256(&data)
}

/// Whether two proofs are the same, in a time that does not depend on where they differ.
pub fn same(a: &[u8; KEY_LEN], b: &[u8; KEY_LEN]) -> bool {
    a.iter().zip(b).fold(0u8, |acc, (x, y)| acc | (x ^ y)) == 0
}

#[cfg(test)]
mod tests {
    use super::*;

    fn hex(bytes: &[u8]) -> String {
        bytes.iter().map(|b| format!("{b:02x}")).collect()
    }

    #[test]
    fn sha256_known_answers() {
        assert_eq!(
            hex(&sha256(b"")),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        );
        assert_eq!(
            hex(&sha256(b"abc")),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
        assert_eq!(
            hex(&sha256(
                b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"
            )),
            "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1"
        );
    }

    #[test]
    fn a_proof_needs_the_password_and_the_challenge() {
        let salt = [7u8; SALT_LEN];
        let host = key(&salt, b"rally");
        let (c1, c2) = ([1u8; SALT_LEN], [2u8; SALT_LEN]);
        assert!(same(&proof(&c1, &host), &proof(&c1, &key(&salt, b"rally"))));
        assert!(!same(
            &proof(&c1, &host),
            &proof(&c1, &key(&salt, b"Rally"))
        ));
        assert!(!same(&proof(&c1, &host), &proof(&c1, &key(&salt, b""))));
        assert!(!same(&proof(&c1, &host), &proof(&c2, &host)));
        assert!(!same(&host, &key(&[8u8; SALT_LEN], b"rally")));
    }
}

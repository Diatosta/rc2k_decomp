//! A session's password: never sent or kept as typed. The host keeps a random salt and the key
//! derived from the salt and the password; a joiner proves it knows the password by answering a
//! fresh challenge with a hash of the challenge and the key it derives from the host's salt, so
//! a recorded answer is no use for another join.

const ROUNDS: u32 = 4096;

/// The size of a key, a proof and a salt's or challenge's bytes.
pub const KEY_LEN: usize = 32;
pub const SALT_LEN: usize = 16;

